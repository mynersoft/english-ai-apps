package com.englishai.app.feature.authentication

import android.content.Context
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import androidx.credentials.exceptions.GetCredentialException
import com.englishai.app.R
import com.google.android.libraries.identity.googleid.GetGoogleIdOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential

/** Gets a Google ID token via Credential Manager. Firebase then exchanges it for a Firebase session. */
object GoogleSignInHelper {
    /** Returns the token, or null if the user cancelled. Throws a readable error otherwise. */
    suspend fun getIdToken(activityContext: Context): String? {
        // default_web_client_id is generated by the google-services plugin from google-services.json
        val webClientId = activityContext.getString(R.string.default_web_client_id)
        val option = GetGoogleIdOption.Builder()
            .setFilterByAuthorizedAccounts(false)
            .setServerClientId(webClientId)
            .build()
        val request = GetCredentialRequest.Builder().addCredentialOption(option).build()
        return try {
            val credential = CredentialManager.create(activityContext)
                .getCredential(activityContext, request).credential
            if (credential is CustomCredential &&
                credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL
            ) {
                GoogleIdTokenCredential.createFrom(credential.data).idToken
            } else error("Unsupported credential type")
        } catch (e: GetCredentialCancellationException) {
            null
        } catch (e: GetCredentialException) {
            error("Google sign-in failed. Check your Google account and try again.")
        }
    }
}
